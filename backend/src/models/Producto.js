class Producto {
    constructor(id, nombre, descripcion, precio, imagen, stock, categoriaId) {
        this.id = id;
        this.nombre = nombre;
        this.descripcion = descripcion;
        this.precio = precio;
        this.imagen = imagen;
        this.stock = stock;
        this.categoriaId = categoriaId;
    }
}

export default Producto;
